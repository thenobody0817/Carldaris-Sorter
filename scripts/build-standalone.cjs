const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

const order = ['catalog.js', 'strings.js', 'model.js', 'storage.js', 'voice.js', 'app.js'];

const strip = source => source
  .replace(/^\s*import\s+[^;]*;\s*$/gm, '')
  .replace(/^export\s+/gm, '');

const body = order.map(name => {
  const source = fs.readFileSync(path.join(root, 'src', name), 'utf8');
  return `// ---- src/${name} ----\n${strip(source).trim()}`;
}).join('\n\n');

const banner = '/* Generated by scripts/build-standalone.cjs. Do not edit directly. Run "npm run build". */\n';
const output = `${banner}(function () {\n'use strict';\n\n${body}\n})();\n`;

fs.writeFileSync(path.join(root, 'app.bundle.js'), output);
console.log(`Built app.bundle.js (${output.length} bytes)`);
